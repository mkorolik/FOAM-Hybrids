def construct_theoretical_puls_pattern_first_order(
    pulsation_grid_file, m1_grid_file, storm_rotation_m1, observations_file,
    output_file, grid_parameters, rotation_source="fit", gmode_rotation_file=None, max_iterations=10,
):
    """
    Match rotationally split p-modes with identified (degree, m) to the first-order rotating
    frequencies f0 + m*beta*Omega_p of every model, where f0 is the m=0 frequency and
    beta = 1 - C_nl = (f_(m=+1) - f0) / Omega_storm comes from a STORM grid of m=+1 modes.
    In the first-order theory beta is the same for every m of a mode (n, l), so one m=+1 grid
    gives the splitting of all m, and a single rotation rate Omega_storm is enough.

    Each observed mode is matched to the nearest candidate of its degree. With
    rotation_source="fit", Omega_p is then fitted in closed form to the observed frequency
    differences within each multiplet (the modes of one degree matched to the same radial order):
        Omega_p = sum u (dm beta)(df) / sum u (dm beta)^2,  u = 1 / (sigma_i^2 + sigma_j^2),
    so that an offset of the model's f0 does not change the rotation rate. Matching and fit are
    iterated until the matched radial orders no longer change. With rotation_source="gmode",
    Omega_p is the rotation rate fitted to the g-mode pattern of the same model.

    Modes without an identified degree are matched to the m=0 frequencies of any degree,
    as in construct_theoretical_puls_pattern_by_degree.

    Parameters
    ----------
    pulsation_grid_file: string
        Grid of m=0 STORM frequencies (columns l{degree}_n_pg{order}).
    m1_grid_file: string
        Grid of m=+1 STORM frequencies of the same models, computed at storm_rotation_m1.
    storm_rotation_m1: float
        Rotation rate (d^-1) of the m=+1 grid.
    observations_file: string
        p-mode observations with columns frequency, frequency_err, degree and m.
    output_file: string
        Written with the same columns as construct_theoretical_puls_pattern_by_degree,
        plus rotp_err; rotp holds Omega_p.
    grid_parameters: list of string
    rotation_source: string
        "fit" or "gmode", see above.
    gmode_rotation_file: string
        g-mode pattern file holding the fitted 'rot' per model, needed for rotation_source="gmode".
    max_iterations: int
        Maximum number of match/fit iterations.
    """
    obs_dataframe = pd.read_table(observations_file, sep=r"\s+", header=0, index_col="index")
    if "m" not in obs_dataframe.columns:
        raise ValueError(f"first-order p-mode matching needs an 'm' column in {observations_file}")
    identified = obs_dataframe["degree"].notna().to_numpy()
    if not identified.any():
        raise ValueError("at least one observed p-mode must have an identified ell")
    degrees = obs_dataframe["degree"].to_numpy()
    mvals = obs_dataframe["m"].to_numpy()
    bad_m = identified & (np.abs(mvals) > np.nan_to_num(degrees))
    if bad_m.any():
        raise ValueError(f"observed p-modes with |m| > ell: rows {list(obs_dataframe.index[bad_m])}")
    if np.any(mvals[~identified] != 0):
        logger.warning("p-modes without an identified degree are matched to m=0 frequencies; their m is ignored")
    f_obs = obs_dataframe["frequency"].to_numpy(dtype=float)
    sigma_obs = obs_dataframe["frequency_err"].to_numpy(dtype=float)

    # Models present in both grids (and, for rotation_source="gmode", in the g-mode patterns)
    theory_m0 = pd.read_hdf(pulsation_grid_file)
    theory_m1 = pd.read_hdf(m1_grid_file).drop(columns=["rotp"], errors="ignore")
    theory_m1 = theory_m1.rename(columns=lambda c: f"m1_{c}" if "_n_pg" in c else c)
    theory = pd.merge(theory_m0, theory_m1, how="inner", on=grid_parameters)
    if rotation_source == "gmode":
        rot_g = pd.read_hdf(gmode_rotation_file)[grid_parameters + ["rot"]]
        theory = pd.merge(theory, rot_g, how="inner", on=grid_parameters)
    if len(theory) < len(theory_m0):
        logger.warning(f"{len(theory_m0) - len(theory)} of {len(theory_m0)} models are missing from the other input grid(s); dropping them")

    # Drop models without modes of every observed degree, as in construct_theoretical_puls_pattern_by_degree
    observed_degrees = sorted({int(ell) for ell in degrees[identified]})
    has_all_degrees = np.ones(len(theory), dtype=bool)
    for ell in observed_degrees:
        has_all_degrees &= theory.filter(regex=rf"^l{ell}_n_pg").notna().sum(axis=1).to_numpy() > 0
    if not has_all_degrees.all():
        logger.warning(f"{(~has_all_degrees).sum()} models have no modes of some observed degree; dropping them")
    theory = theory[has_all_degrees].reset_index(drop=True)
    if theory.empty:
        raise ValueError("no model has modes for every observed degree")
    n_models = len(theory)

    # f0 and beta per degree, as (models x radial orders) arrays
    f0, beta = {}, {}
    for ell in observed_degrees:
        cols = list(theory.filter(regex=rf"^l{ell}_n_pg").columns)
        f0[ell] = theory[cols].to_numpy(dtype=float)
        m1_cols = [f"m1_{c}" for c in cols]
        if ell == 0:
            beta[ell] = np.zeros_like(f0[ell])
        else:
            f1 = theory.reindex(columns=m1_cols).to_numpy(dtype=float)
            beta[ell] = (f1 - f0[ell]) / storm_rotation_m1

    rows_of_degree = {ell: np.where(identified & (degrees == ell))[0] for ell in observed_degrees}
    # Pairs of observed modes of one degree with different m: the differences that constrain Omega_p
    pairs = [
        (ell, i, j)
        for ell, rows in rows_of_degree.items()
        for a, i in enumerate(rows) for j in rows[a + 1:]
        if mvals[i] != mvals[j]
    ]
    if rotation_source == "fit" and not pairs:
        raise ValueError("pmode_rotation='fit' needs at least two observed modes of one degree with different m")

    def split_frequencies(ell, i, omega):
        """Candidate frequencies of observed mode i for every model and radial order."""
        if mvals[i] == 0:
            # needs no splitting, so orders missing from the m=+1 grid remain candidates
            return f0[ell]
        return f0[ell] + mvals[i] * beta[ell] * omega[:, np.newaxis]

    def match(omega):
        """Index of the matched radial order of every identified mode, per model."""
        matched = {}
        for ell, rows in rows_of_degree.items():
            for i in rows:
                distance = np.abs(split_frequencies(ell, i, omega) - f_obs[i])
                # orders without an m=0 frequency, or without a splitting for m != 0, are no candidates
                distance = np.where(np.isnan(distance), np.inf, distance)
                matched[i] = np.argmin(distance, axis=1)
        return matched

    def beta_at(ell, idx):
        return beta[ell][np.arange(n_models), idx]

    if rotation_source == "gmode":
        omega = theory["rot"].to_numpy(dtype=float)
        omega_err = np.zeros(n_models)
        matched = match(omega)
    else:
        omega = np.zeros(n_models)
        omega_err = np.full(n_models, np.nan)
        matched = match(omega)
        for iteration in range(max_iterations):
            numerator = np.zeros(n_models)
            denominator = np.zeros(n_models)
            for ell, i, j in pairs:
                same_multiplet = matched[i] == matched[j]
                x = (mvals[i] - mvals[j]) * beta_at(ell, matched[i])
                u = 1.0 / (sigma_obs[i] ** 2 + sigma_obs[j] ** 2)
                ok = same_multiplet & np.isfinite(x)
                numerator += np.where(ok, u * x * (f_obs[i] - f_obs[j]), 0.0)
                denominator += np.where(ok, u * x**2, 0.0)
            constrained = denominator > 0
            # A model whose matches put no two modes in one multiplet has no splitting to fit;
            # it keeps Omega_p = 0 and pays for the unexplained splitting in its residuals.
            omega = np.where(constrained, numerator / np.where(constrained, denominator, 1.0), 0.0)
            omega_err = np.where(constrained, 1.0 / np.sqrt(np.where(constrained, denominator, 1.0)), np.nan)
            new_matched = match(omega)
            if all(np.array_equal(new_matched[i], matched[i]) for i in matched):
                break
            matched = new_matched
        else:
            logger.warning(f"p-mode matching and Omega_p fit not converged after {max_iterations} iterations")
        logger.info(
            f"Omega_p fitted for {constrained.sum()} of {n_models} models; "
            f"median {np.median(omega[constrained]) if constrained.any() else np.nan:.5f} d^-1"
        )

    combined = theory[grid_parameters].copy()
    combined["rotp"] = omega
    combined["rotp_err"] = omega_err
    for ell, rows in rows_of_degree.items():
        for i in rows:
            combined[f"frequency{i + 1}"] = split_frequencies(ell, i, omega)[np.arange(n_models), matched[i]]

    global_rows_unidentified = [i + 1 for i in np.where(~identified)[0]]
    if global_rows_unidentified:
        theory_m0_only = theory[grid_parameters + list(theory.filter(regex=r"^l\d+_n_pg").columns)]
        unidentified_df = match_unidentified_nearest_any_degree(theory_m0_only, obs_dataframe, global_rows_unidentified)
        combined = pd.concat([combined, unidentified_df.reset_index(drop=True)], axis=1)

    # Same column order as construct_theoretical_puls_pattern_by_degree: observations-file order
    ordered_columns = grid_parameters + ["rotp", "rotp_err"]
    for global_i in range(1, len(obs_dataframe) + 1):
        ordered_columns.append(f"frequency{global_i}")
        if f"logdensity{global_i}" in combined.columns:
            ordered_columns.append(f"logdensity{global_i}")
    combined = combined[ordered_columns]

    Path(Path(output_file).parent).mkdir(parents=True, exist_ok=True)
    combined.to_hdf(path_or_buf=output_file, key="selected_puls_grid", format="table", mode="w")


