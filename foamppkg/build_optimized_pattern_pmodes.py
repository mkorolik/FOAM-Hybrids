def construct_theoretical_puls_pattern_by_degree(
    pulsation_grid_file, observations_file, method_build_series,
    output_file, grid_parameters, nr_cpu=None, tmp_dir="tmp_degree_split",
):
    obs_dataframe = pd.read_table(observations_file, sep="\s+", header=0, index_col="index")
    if obs_dataframe["degree"].notna().sum() == 0:
        raise ValueError("at least one observed p-mode must have an identified ell")

    theory_dataframe = pd.read_hdf(pulsation_grid_file)
    Path(tmp_dir).mkdir(parents=True, exist_ok=True)

    # A model with no computed modes of an observed degree (e.g. near-ZAMS models whose
    # radial fundamental lies above the grid's frequency window) cannot match that mode,
    # and would leave nothing to select from. Drop such models once, up front, so the
    # per-degree results and the unidentified-mode matches below stay row-aligned.
    has_all_degrees = pd.Series(True, index=theory_dataframe.index)
    for ell in obs_dataframe["degree"].dropna().unique():
        ell = int(ell)
        n_modes = theory_dataframe.filter(like=f"l{ell}_n_pg").notna().sum(axis=1)
        if (n_modes == 0).any():
            logger.warning(
                f"{(n_modes == 0).sum()} of {len(theory_dataframe)} models have no ell={ell} modes "
                f"in {pulsation_grid_file}; dropping them"
            )
        has_all_degrees &= n_modes > 0
    theory_dataframe = theory_dataframe[has_all_degrees].reset_index(drop=True)
    if theory_dataframe.empty:
        raise ValueError(f"no model in {pulsation_grid_file} has modes for every observed degree")

    per_degree_results = {}
    per_degree_global_rows = {}   # global row positions (1-indexed) each ell subset corresponds to, in order


    for ell in sorted(obs_dataframe["degree"].dropna().unique()):
        ell = int(ell)

        obs_subset = obs_dataframe[obs_dataframe["degree"] == ell]          # real rows only, no masking

        method_for_this_ell = method_build_series
        if method_build_series == "chisq-longest-sequence" and len(obs_subset) < 2:
            logger.warning(
                f"only {len(obs_subset)} observed mode(s) with ell={ell}; "
                f"chisq-longest-sequence is undefined for <2 points, falling back to highest-frequency"
            )
            method_for_this_ell = "highest-frequency"


        global_rows = [i for i, (_, row) in enumerate(obs_dataframe.iterrows(), start=1) if row["degree"] == ell]
        per_degree_global_rows[ell] = global_rows

        obs_tmp_path = f"{tmp_dir}/obs_l{ell}.tsv"
        obs_subset.to_csv(obs_tmp_path, sep="\t")

        keep_cols = grid_parameters + ["rotp"] + list(theory_dataframe.filter(like=f"l{ell}_n_pg").columns)
        theory_subset = theory_dataframe[keep_cols].rename(
            columns=lambda c: c.replace(f"l{ell}_n_pg", "n_pg") if c.startswith(f"l{ell}_n_pg") else c
        )  

        theory_tmp_path = f"{tmp_dir}/theory_l{ell}.hdf"
        theory_subset.to_hdf(theory_tmp_path, key="pulsation_grid", format="table", mode="w")

        out_path = f"{tmp_dir}/pattern_l{ell}.hdf"
        construct_theoretical_puls_pattern(
            theory_tmp_path, obs_tmp_path, method_for_this_ell,
            which_observable="frequency", output_file=out_path,
            asymptotic_object=None, estimated_rotation=None,
            grid_parameters=grid_parameters, nr_cpu=nr_cpu,
        )
        per_degree_results[ell] = pd.read_hdf(out_path)

        

    combined = per_degree_results[next(iter(per_degree_results))][grid_parameters + ["rotp"]].copy()
    for ell, global_rows in per_degree_global_rows.items():
        result_df = per_degree_results[ell]
        for local_i, global_i in enumerate(global_rows, start=1):
            combined[f"frequency{global_i}"] = result_df[f"frequency{local_i}"]

    global_rows_unidentified = [i for i, (_, row) in enumerate(obs_dataframe.iterrows(), start=1) if pd.isna(row["degree"])]
    
    if global_rows_unidentified:
        unidentified_df = match_unidentified_nearest_any_degree(theory_dataframe, obs_dataframe, global_rows_unidentified)
        combined = pd.concat([combined.reset_index(drop=True), unidentified_df.reset_index(drop=True)], axis=1)

    # The columns were filled one degree at a time, but the likelihood step pairs
    # them with the observations positionally (filter(like="frequency")), so put
    # them back in the row order of the observations file.
    ordered_columns = grid_parameters + ["rotp"]
    for global_i in range(1, len(obs_dataframe) + 1):
        ordered_columns.append(f"frequency{global_i}")
        if f"logdensity{global_i}" in combined.columns:
            ordered_columns.append(f"logdensity{global_i}")
    combined = combined[ordered_columns]

    # One frequency column per observed mode, plus the extra logdensity column that
    # each unidentified mode carries alongside its match.
    expected_columns = len(grid_parameters) + 1 + len(obs_dataframe) + len(global_rows_unidentified)
    assert combined.shape[1] == expected_columns, (
        f"expected {expected_columns} columns in the combined identified + unidentified "
        f"dataframe ({len(grid_parameters)} grid parameters + rotp + {len(obs_dataframe)} "
        f"observed modes + {len(global_rows_unidentified)} logdensity), got {combined.shape[1]}"
    )

    Path(Path(output_file).parent).mkdir(parents=True, exist_ok=True)
    combined.to_hdf(path_or_buf=output_file, key="selected_puls_grid", format="table", mode="w")



def match_unidentified_nearest_any_degree(
    theory_dataframe, obs_dataframe, global_rows_unidentified, density_window=1.5
):
    """
    For each model row, and each unidentified observed frequency, find whichever
    theoretical frequency (pooled across all available degrees) is numerically
    closest. No sequence/ladder assumption -- just a per-model nearest-neighbour
    match, since the degree is genuinely unknown.

    Also record the local theoretical mode density around each observed frequency.
    A nearest-neighbour match is biased in favour of models with denser spectra:
    for a spectrum of local density rho, E|f_obs - f_nearest| goes as 1/(2*rho),
    so a model that packs more modes into the observed range wins on residual
    alone, regardless of whether it is a better description of the star. Charging
    it the uniform 1/N prior over which mode the observation could have been is
    what cancels that, and the density is the model-dependent half of that prior.
    Recording it here keeps the bookkeeping next to the match that creates the
    need for it; how it enters the merit function is the caller's decision.

    Parameters
    ----------
    theory_dataframe: pandas DataFrame
        Theoretical grid, with one column per (degree, radial order).
    obs_dataframe: pandas DataFrame
        The observations, indexed as in the observations file.
    global_rows_unidentified: list of int
        1-indexed positions, within obs_dataframe, of the modes with no identified degree.
    density_window: float
        Half-width, in the same unit as the frequencies, of the window used to
        estimate the local mode density. Must be identical for every model, and
        wide enough to hold several modes for the sparsest models in the grid.
        Its absolute value cancels out of any comparison between models, since it
        shifts every model's density by the same constant factor.

    Returns
    ----------
    result: pandas DataFrame
        Column "frequency{i}" holds the matched theoretical value and
        "logdensity{i}" the log of the local mode density, for each unidentified
        observed mode i.
    """
    pooled_cols = list(theory_dataframe.filter(regex=r"^l\d+_n_pg").columns)
    freqs = theory_dataframe[pooled_cols].to_numpy(dtype=float)
    result = pd.DataFrame(index=theory_dataframe.index)

    for global_i in global_rows_unidentified:
        obs_freq = obs_dataframe.loc[obs_dataframe.index[global_i - 1], "frequency"]
        # NaN entries are orders GYRE did not return for that model, so they are
        # not candidates; +inf keeps them out of both the argmin and the count.
        distance = np.abs(freqs - obs_freq)
        distance = np.where(np.isnan(distance), np.inf, distance)

        nearest = np.argmin(distance, axis=1)
        result[f"frequency{global_i}"] = freqs[np.arange(len(freqs)), nearest]

        n_in_window = (distance <= density_window).sum(axis=1)
        # A model with nothing in the window is not infinitely improbable, just a
        # bad match: floor the count at one so it pays no density penalty and is
        # judged on its (large) residual alone.
        result[f"logdensity{global_i}"] = np.log(
            np.maximum(n_in_window, 1) / (2.0 * density_window)
        )

    return result


